/* PIM IV - 01_schema.sql | PostgreSQL 15+ (Supabase) | idempotente
   Schema dedicado "pim": não fica exposto pela Data API (PostgREST) do Supabase.
   Convenção: snake_case (o EF Core usa UseSnakeCaseNamingConvention). */

CREATE SCHEMA IF NOT EXISTS pim;

/* ---------- usuarios ---------- */
CREATE TABLE IF NOT EXISTS pim.usuarios (
    id                 integer GENERATED BY DEFAULT AS IDENTITY,
    nome               varchar(150) NOT NULL,
    email              varchar(200) NOT NULL,
    senha_hash         varchar(200) NOT NULL,
    perfil             varchar(20)  NOT NULL,
    ativo              boolean      NOT NULL DEFAULT true,
    tentativas_falhas  integer      NOT NULL DEFAULT 0,
    bloqueado_ate      timestamptz  NULL,
    data_criacao       timestamptz  NOT NULL DEFAULT now(),
    data_atualizacao   timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT pk_usuarios PRIMARY KEY (id),
    CONSTRAINT uq_usuarios_email UNIQUE (email),
    CONSTRAINT ck_usuarios_perfil CHECK (perfil IN ('Admin', 'Gestor', 'Colaborador'))
);

/* ---------- refresh_tokens (apenas hash) ---------- */
CREATE TABLE IF NOT EXISTS pim.refresh_tokens (
    id                    integer GENERATED BY DEFAULT AS IDENTITY,
    usuario_id            integer      NOT NULL,
    token_hash            varchar(64)  NOT NULL,   -- SHA-256 hex
    data_criacao          timestamptz  NOT NULL DEFAULT now(),
    data_expiracao        timestamptz  NOT NULL,
    data_revogacao        timestamptz  NULL,
    substituido_por_hash  varchar(64)  NULL,
    CONSTRAINT pk_refresh_tokens PRIMARY KEY (id),
    CONSTRAINT uq_refresh_tokens_hash UNIQUE (token_hash),
    CONSTRAINT fk_refresh_tokens_usuarios FOREIGN KEY (usuario_id) REFERENCES pim.usuarios (id)
);
CREATE INDEX IF NOT EXISTS ix_refresh_tokens_usuario_id ON pim.refresh_tokens (usuario_id);

/* ---------- colaboradores ---------- */
CREATE TABLE IF NOT EXISTS pim.colaboradores (
    id                integer GENERATED BY DEFAULT AS IDENTITY,
    nome              varchar(150) NOT NULL,
    email             varchar(200) NULL,
    cargo             varchar(100) NULL,
    ativo             boolean      NOT NULL DEFAULT true,
    usuario_id        integer      NULL,
    data_criacao      timestamptz  NOT NULL DEFAULT now(),
    data_atualizacao  timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT pk_colaboradores PRIMARY KEY (id),
    CONSTRAINT fk_colaboradores_usuarios FOREIGN KEY (usuario_id) REFERENCES pim.usuarios (id)
);
-- usuario_id nulo e único / e-mail único quando informado (índices parciais)
CREATE UNIQUE INDEX IF NOT EXISTS ux_colaboradores_usuario_id ON pim.colaboradores (usuario_id) WHERE usuario_id IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS ux_colaboradores_email ON pim.colaboradores (email) WHERE email IS NOT NULL;

/* ---------- equipes e N:N ---------- */
CREATE TABLE IF NOT EXISTS pim.equipes (
    id         integer GENERATED BY DEFAULT AS IDENTITY,
    nome       varchar(100) NOT NULL,
    descricao  varchar(500) NULL,
    CONSTRAINT pk_equipes PRIMARY KEY (id),
    CONSTRAINT uq_equipes_nome UNIQUE (nome)
);

CREATE TABLE IF NOT EXISTS pim.equipe_colaboradores (
    equipe_id       integer     NOT NULL,
    colaborador_id  integer     NOT NULL,
    data_entrada    timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT pk_equipe_colaboradores PRIMARY KEY (equipe_id, colaborador_id),
    CONSTRAINT fk_equipe_colab_equipes FOREIGN KEY (equipe_id) REFERENCES pim.equipes (id) ON DELETE CASCADE,
    CONSTRAINT fk_equipe_colab_colaboradores FOREIGN KEY (colaborador_id) REFERENCES pim.colaboradores (id)
);
CREATE INDEX IF NOT EXISTS ix_equipe_colaboradores_colaborador_id ON pim.equipe_colaboradores (colaborador_id);

/* ---------- tarefas ---------- */
CREATE TABLE IF NOT EXISTS pim.tarefas (
    id                integer GENERATED BY DEFAULT AS IDENTITY,
    titulo            varchar(200)  NOT NULL,
    descricao         varchar(2000) NOT NULL DEFAULT '',
    status            varchar(20)   NOT NULL DEFAULT 'Pendente',
    prioridade        varchar(20)   NOT NULL DEFAULT 'Media',
    data_prazo        timestamptz   NULL,
    colaborador_id    integer       NULL,
    equipe_id         integer       NULL,
    excluida          boolean       NOT NULL DEFAULT false,   -- remoção lógica (sync mobile)
    data_criacao      timestamptz   NOT NULL DEFAULT now(),
    data_atualizacao  timestamptz   NOT NULL DEFAULT now(),
    CONSTRAINT pk_tarefas PRIMARY KEY (id),
    CONSTRAINT fk_tarefas_colaboradores FOREIGN KEY (colaborador_id) REFERENCES pim.colaboradores (id),
    CONSTRAINT fk_tarefas_equipes FOREIGN KEY (equipe_id) REFERENCES pim.equipes (id),
    CONSTRAINT ck_tarefas_status CHECK (status IN ('Pendente', 'EmAndamento', 'Concluida')),
    CONSTRAINT ck_tarefas_prioridade CHECK (prioridade IN ('Baixa', 'Media', 'Alta', 'Urgente'))
);
CREATE INDEX IF NOT EXISTS ix_tarefas_status           ON pim.tarefas (status);
CREATE INDEX IF NOT EXISTS ix_tarefas_colaborador_id   ON pim.tarefas (colaborador_id);
CREATE INDEX IF NOT EXISTS ix_tarefas_data_atualizacao ON pim.tarefas (data_atualizacao);
CREATE INDEX IF NOT EXISTS ix_tarefas_equipe_id        ON pim.tarefas (equipe_id);

/* ---------- comentários e histórico ---------- */
CREATE TABLE IF NOT EXISTS pim.tarefa_comentarios (
    id            integer GENERATED BY DEFAULT AS IDENTITY,
    tarefa_id     integer       NOT NULL,
    usuario_id    integer       NOT NULL,
    texto         varchar(1000) NOT NULL,
    data_criacao  timestamptz   NOT NULL DEFAULT now(),
    CONSTRAINT pk_tarefa_comentarios PRIMARY KEY (id),
    CONSTRAINT fk_tarefa_comentarios_tarefas FOREIGN KEY (tarefa_id) REFERENCES pim.tarefas (id),
    CONSTRAINT fk_tarefa_comentarios_usuarios FOREIGN KEY (usuario_id) REFERENCES pim.usuarios (id),
    CONSTRAINT ck_tarefa_comentarios_texto CHECK (length(btrim(texto)) > 0)
);
CREATE INDEX IF NOT EXISTS ix_tarefa_comentarios_tarefa_id ON pim.tarefa_comentarios (tarefa_id, data_criacao);

CREATE TABLE IF NOT EXISTS pim.tarefa_historico (
    id               integer GENERATED BY DEFAULT AS IDENTITY,
    tarefa_id        integer      NOT NULL,
    status_anterior  varchar(20)  NOT NULL,
    status_novo      varchar(20)  NOT NULL,
    usuario_id       integer      NULL,
    data_alteracao   timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT pk_tarefa_historico PRIMARY KEY (id),
    CONSTRAINT fk_tarefa_historico_tarefas FOREIGN KEY (tarefa_id) REFERENCES pim.tarefas (id),
    CONSTRAINT fk_tarefa_historico_usuarios FOREIGN KEY (usuario_id) REFERENCES pim.usuarios (id),
    CONSTRAINT ck_tarefa_historico_status CHECK (
        status_anterior IN ('Pendente', 'EmAndamento', 'Concluida') AND
        status_novo     IN ('Pendente', 'EmAndamento', 'Concluida'))
);
CREATE INDEX IF NOT EXISTS ix_tarefa_historico_tarefa_id ON pim.tarefa_historico (tarefa_id, data_alteracao);

/* ---------- view ---------- */
CREATE OR REPLACE VIEW pim.vw_tarefas_detalhadas WITH (security_invoker = true) AS
SELECT t.id, t.titulo, t.descricao, t.status, t.prioridade, t.data_prazo, t.excluida,
       t.data_criacao, t.data_atualizacao,
       t.colaborador_id, c.nome AS colaborador_nome, c.cargo AS colaborador_cargo,
       t.equipe_id,      e.nome AS equipe_nome
FROM pim.tarefas t
LEFT JOIN pim.colaboradores c ON c.id = t.colaborador_id
LEFT JOIN pim.equipes e       ON e.id = t.equipe_id;
/* PIM IV - 02_procedures.sql | idempotente (CREATE OR REPLACE)
   Erros de negócio (SQLSTATE): PM001 não encontrada | PM002 tarefa excluída | PM003 já concluída
                                PM004 colaborador inválido/inativo
   Equivalência com o T-SQL: BEGIN..EXCEPTION = TRY/CATCH (cria subtransação), RAISE = THROW.
   Procedimentos que devolvem linhas (relatórios) são FUNCTIONs RETURNS TABLE: no PostgreSQL uma PROCEDURE não retorna result set. */

CREATE OR REPLACE PROCEDURE pim.sp_concluir_tarefa(p_tarefa_id integer, p_usuario_id integer DEFAULT NULL)
LANGUAGE plpgsql
SET search_path = pim, pg_temp
AS $$
DECLARE
    v_status   varchar(20);
    v_excluida boolean;
BEGIN
    SELECT status, excluida INTO v_status, v_excluida FROM pim.tarefas WHERE id = p_tarefa_id FOR UPDATE;

    IF NOT FOUND        THEN RAISE EXCEPTION 'Tarefa não encontrada.' USING ERRCODE = 'PM001'; END IF;
    IF v_excluida       THEN RAISE EXCEPTION 'Não é possível concluir uma tarefa excluída.' USING ERRCODE = 'PM002'; END IF;
    IF v_status = 'Concluida' THEN RAISE EXCEPTION 'A tarefa já está concluída.' USING ERRCODE = 'PM003'; END IF;

    -- usuário lido pela trigger de histórico (vale só até o fim da transação)
    PERFORM set_config('app.usuario_id', COALESCE(p_usuario_id::text, ''), true);
    UPDATE pim.tarefas SET status = 'Concluida' WHERE id = p_tarefa_id;
EXCEPTION
    WHEN OTHERS THEN
        RAISE;   -- relança o erro original (o PostgreSQL desfaz as alterações do bloco)
END;
$$;

CREATE OR REPLACE PROCEDURE pim.sp_reatribuir_tarefa(p_tarefa_id integer, p_novo_colaborador_id integer DEFAULT NULL, p_usuario_id integer DEFAULT NULL)
LANGUAGE plpgsql
SET search_path = pim, pg_temp
AS $$
DECLARE
    v_excluida boolean;
BEGIN
    SELECT excluida INTO v_excluida FROM pim.tarefas WHERE id = p_tarefa_id FOR UPDATE;

    IF NOT FOUND  THEN RAISE EXCEPTION 'Tarefa não encontrada.' USING ERRCODE = 'PM001'; END IF;
    IF v_excluida THEN RAISE EXCEPTION 'Não é possível reatribuir uma tarefa excluída.' USING ERRCODE = 'PM002'; END IF;
    IF p_novo_colaborador_id IS NOT NULL
       AND NOT EXISTS (SELECT 1 FROM pim.colaboradores WHERE id = p_novo_colaborador_id AND ativo)
    THEN RAISE EXCEPTION 'O colaborador informado não existe ou está inativo.' USING ERRCODE = 'PM004'; END IF;

    PERFORM set_config('app.usuario_id', COALESCE(p_usuario_id::text, ''), true);
    UPDATE pim.tarefas SET colaborador_id = p_novo_colaborador_id WHERE id = p_tarefa_id;
EXCEPTION
    WHEN OTHERS THEN
        RAISE;
END;
$$;

CREATE OR REPLACE FUNCTION pim.sp_resumo_tarefas_por_colaborador()
RETURNS TABLE (colaborador_id integer, colaborador_nome text, total integer, pendentes integer, em_andamento integer, concluidas integer)
LANGUAGE plpgsql STABLE
SET search_path = pim, pg_temp
AS $$
BEGIN
    RETURN QUERY
    SELECT c.id, c.nome::text,
           COUNT(t.id)::integer,
           COALESCE(SUM(CASE WHEN t.status = 'Pendente'    THEN 1 ELSE 0 END), 0)::integer,
           COALESCE(SUM(CASE WHEN t.status = 'EmAndamento' THEN 1 ELSE 0 END), 0)::integer,
           COALESCE(SUM(CASE WHEN t.status = 'Concluida'   THEN 1 ELSE 0 END), 0)::integer
      FROM pim.colaboradores c
      LEFT JOIN pim.tarefas t ON t.colaborador_id = c.id AND NOT t.excluida
     WHERE c.ativo
     GROUP BY c.id, c.nome
     ORDER BY c.nome;
EXCEPTION
    WHEN OTHERS THEN
        RAISE;
END;
$$;

CREATE OR REPLACE FUNCTION pim.sp_tarefas_atrasadas()
RETURNS TABLE (id integer, titulo text, status text, prioridade text, data_prazo timestamptz, dias_atraso integer,
               colaborador_id integer, colaborador_nome text, equipe_id integer, equipe_nome text)
LANGUAGE plpgsql STABLE
SET search_path = pim, pg_temp
AS $$
BEGIN
    RETURN QUERY
    SELECT v.id, v.titulo::text, v.status::text, v.prioridade::text, v.data_prazo,
           GREATEST(EXTRACT(DAY FROM (now() - v.data_prazo))::integer, 0),
           v.colaborador_id, v.colaborador_nome::text, v.equipe_id, v.equipe_nome::text
      FROM pim.vw_tarefas_detalhadas v
     WHERE NOT v.excluida AND v.status <> 'Concluida'
       AND v.data_prazo IS NOT NULL AND v.data_prazo < now()
     ORDER BY v.data_prazo;
EXCEPTION
    WHEN OTHERS THEN
        RAISE;
END;
$$;
/* PIM IV - 03_triggers.sql | idempotente (CREATE OR REPLACE + DROP TRIGGER IF EXISTS) */

-- Histórico de status. O usuário vem de current_setting('app.usuario_id'), definido pela API/procedures na transação.
CREATE OR REPLACE FUNCTION pim.fn_tarefas_historico() RETURNS trigger
LANGUAGE plpgsql SET search_path = pim, pg_temp
AS $$
BEGIN
    INSERT INTO pim.tarefa_historico (tarefa_id, status_anterior, status_novo, usuario_id)
    VALUES (NEW.id, OLD.status, NEW.status, NULLIF(current_setting('app.usuario_id', true), '')::integer);
    RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS trg_tarefas_historico ON pim.tarefas;
CREATE TRIGGER trg_tarefas_historico AFTER UPDATE ON pim.tarefas
    FOR EACH ROW WHEN (OLD.status IS DISTINCT FROM NEW.status)
    EXECUTE FUNCTION pim.fn_tarefas_historico();

-- data_atualizacao (BEFORE: o valor novo já sai no RETURNING do EF Core)
CREATE OR REPLACE FUNCTION pim.fn_atualiza_data_atualizacao() RETURNS trigger
LANGUAGE plpgsql SET search_path = pim, pg_temp
AS $$
BEGIN
    NEW.data_atualizacao := clock_timestamp();   -- now() seria o início da transação
    RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS trg_tarefas_data_atualizacao ON pim.tarefas;
CREATE TRIGGER trg_tarefas_data_atualizacao BEFORE UPDATE ON pim.tarefas
    FOR EACH ROW EXECUTE FUNCTION pim.fn_atualiza_data_atualizacao();
DROP TRIGGER IF EXISTS trg_colaboradores_data_atualizacao ON pim.colaboradores;
CREATE TRIGGER trg_colaboradores_data_atualizacao BEFORE UPDATE ON pim.colaboradores
    FOR EACH ROW EXECUTE FUNCTION pim.fn_atualiza_data_atualizacao();
DROP TRIGGER IF EXISTS trg_usuarios_data_atualizacao ON pim.usuarios;
CREATE TRIGGER trg_usuarios_data_atualizacao BEFORE UPDATE ON pim.usuarios
    FOR EACH ROW EXECUTE FUNCTION pim.fn_atualiza_data_atualizacao();

-- Exclusão de colaborador: com tarefas abertas => apenas inativa (cancela o DELETE); sem => exclui de fato.
-- (PostgreSQL não tem INSTEAD OF DELETE em tabelas; BEFORE DELETE retornando NULL cancela a exclusão da linha.)
CREATE OR REPLACE FUNCTION pim.fn_colaboradores_bloqueia_exclusao() RETURNS trigger
LANGUAGE plpgsql SET search_path = pim, pg_temp
AS $$
BEGIN
    IF EXISTS (SELECT 1 FROM pim.tarefas t
                WHERE t.colaborador_id = OLD.id AND NOT t.excluida AND t.status <> 'Concluida') THEN
        UPDATE pim.colaboradores SET ativo = false WHERE id = OLD.id;
        RETURN NULL;   -- cancela o DELETE
    END IF;

    DELETE FROM pim.equipe_colaboradores WHERE colaborador_id = OLD.id;
    UPDATE pim.tarefas SET colaborador_id = NULL WHERE colaborador_id = OLD.id;   -- preserva o histórico das tarefas
    RETURN OLD;
END;
$$;
DROP TRIGGER IF EXISTS trg_colaboradores_bloqueia_exclusao_com_tarefas ON pim.colaboradores;
CREATE TRIGGER trg_colaboradores_bloqueia_exclusao_com_tarefas BEFORE DELETE ON pim.colaboradores
    FOR EACH ROW EXECUTE FUNCTION pim.fn_colaboradores_bloqueia_exclusao();
