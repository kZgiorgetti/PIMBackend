/* PIM IV - 01_schema.sql | PostgreSQL 15+ (Supabase) | idempotente
   Schema dedicado "pim": não fica exposto pela Data API (PostgREST) do Supabase.
   Convenção: snake_case (o EF Core usa UseSnakeCaseNamingConvention). */

CREATE SCHEMA IF NOT EXISTS pim;

/* ---------- usuarios ---------- */
CREATE TABLE IF NOT EXISTS pim.usuarios (
    id                 integer GENERATED BY DEFAULT AS IDENTITY,
    nome               varchar(150) NOT NULL,
    email              varchar(200) NOT NULL,
    senha_hash         varchar(200) NOT NULL,
    perfil             varchar(20)  NOT NULL,
    ativo              boolean      NOT NULL DEFAULT true,
    tentativas_falhas  integer      NOT NULL DEFAULT 0,
    bloqueado_ate      timestamptz  NULL,
    data_criacao       timestamptz  NOT NULL DEFAULT now(),
    data_atualizacao   timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT pk_usuarios PRIMARY KEY (id),
    CONSTRAINT uq_usuarios_email UNIQUE (email),
    CONSTRAINT ck_usuarios_perfil CHECK (perfil IN ('Admin', 'Gestor', 'Colaborador'))
);

/* ---------- refresh_tokens (apenas hash) ---------- */
CREATE TABLE IF NOT EXISTS pim.refresh_tokens (
    id                    integer GENERATED BY DEFAULT AS IDENTITY,
    usuario_id            integer      NOT NULL,
    token_hash            varchar(64)  NOT NULL,   -- SHA-256 hex
    data_criacao          timestamptz  NOT NULL DEFAULT now(),
    data_expiracao        timestamptz  NOT NULL,
    data_revogacao        timestamptz  NULL,
    substituido_por_hash  varchar(64)  NULL,
    CONSTRAINT pk_refresh_tokens PRIMARY KEY (id),
    CONSTRAINT uq_refresh_tokens_hash UNIQUE (token_hash),
    CONSTRAINT fk_refresh_tokens_usuarios FOREIGN KEY (usuario_id) REFERENCES pim.usuarios (id)
);
CREATE INDEX IF NOT EXISTS ix_refresh_tokens_usuario_id ON pim.refresh_tokens (usuario_id);

/* ---------- colaboradores ---------- */
CREATE TABLE IF NOT EXISTS pim.colaboradores (
    id                integer GENERATED BY DEFAULT AS IDENTITY,
    nome              varchar(150) NOT NULL,
    email             varchar(200) NULL,
    cargo             varchar(100) NULL,
    ativo             boolean      NOT NULL DEFAULT true,
    usuario_id        integer      NULL,
    data_criacao      timestamptz  NOT NULL DEFAULT now(),
    data_atualizacao  timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT pk_colaboradores PRIMARY KEY (id),
    CONSTRAINT fk_colaboradores_usuarios FOREIGN KEY (usuario_id) REFERENCES pim.usuarios (id)
);
-- usuario_id nulo e único / e-mail único quando informado (índices parciais)
CREATE UNIQUE INDEX IF NOT EXISTS ux_colaboradores_usuario_id ON pim.colaboradores (usuario_id) WHERE usuario_id IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS ux_colaboradores_email ON pim.colaboradores (email) WHERE email IS NOT NULL;

/* ---------- equipes e N:N ---------- */
CREATE TABLE IF NOT EXISTS pim.equipes (
    id         integer GENERATED BY DEFAULT AS IDENTITY,
    nome       varchar(100) NOT NULL,
    descricao  varchar(500) NULL,
    CONSTRAINT pk_equipes PRIMARY KEY (id),
    CONSTRAINT uq_equipes_nome UNIQUE (nome)
);

CREATE TABLE IF NOT EXISTS pim.equipe_colaboradores (
    equipe_id       integer     NOT NULL,
    colaborador_id  integer     NOT NULL,
    data_entrada    timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT pk_equipe_colaboradores PRIMARY KEY (equipe_id, colaborador_id),
    CONSTRAINT fk_equipe_colab_equipes FOREIGN KEY (equipe_id) REFERENCES pim.equipes (id) ON DELETE CASCADE,
    CONSTRAINT fk_equipe_colab_colaboradores FOREIGN KEY (colaborador_id) REFERENCES pim.colaboradores (id)
);
CREATE INDEX IF NOT EXISTS ix_equipe_colaboradores_colaborador_id ON pim.equipe_colaboradores (colaborador_id);

/* ---------- tarefas ---------- */
CREATE TABLE IF NOT EXISTS pim.tarefas (
    id                integer GENERATED BY DEFAULT AS IDENTITY,
    titulo            varchar(200)  NOT NULL,
    descricao         varchar(2000) NOT NULL DEFAULT '',
    status            varchar(20)   NOT NULL DEFAULT 'Pendente',
    prioridade        varchar(20)   NOT NULL DEFAULT 'Media',
    data_prazo        timestamptz   NULL,
    colaborador_id    integer       NULL,
    equipe_id         integer       NULL,
    excluida          boolean       NOT NULL DEFAULT false,   -- remoção lógica (sync mobile)
    data_criacao      timestamptz   NOT NULL DEFAULT now(),
    data_atualizacao  timestamptz   NOT NULL DEFAULT now(),
    CONSTRAINT pk_tarefas PRIMARY KEY (id),
    CONSTRAINT fk_tarefas_colaboradores FOREIGN KEY (colaborador_id) REFERENCES pim.colaboradores (id),
    CONSTRAINT fk_tarefas_equipes FOREIGN KEY (equipe_id) REFERENCES pim.equipes (id),
    CONSTRAINT ck_tarefas_status CHECK (status IN ('Pendente', 'EmAndamento', 'Concluida')),
    CONSTRAINT ck_tarefas_prioridade CHECK (prioridade IN ('Baixa', 'Media', 'Alta', 'Urgente'))
);
CREATE INDEX IF NOT EXISTS ix_tarefas_status           ON pim.tarefas (status);
CREATE INDEX IF NOT EXISTS ix_tarefas_colaborador_id   ON pim.tarefas (colaborador_id);
CREATE INDEX IF NOT EXISTS ix_tarefas_data_atualizacao ON pim.tarefas (data_atualizacao);
CREATE INDEX IF NOT EXISTS ix_tarefas_equipe_id        ON pim.tarefas (equipe_id);

/* ---------- comentários e histórico ---------- */
CREATE TABLE IF NOT EXISTS pim.tarefa_comentarios (
    id            integer GENERATED BY DEFAULT AS IDENTITY,
    tarefa_id     integer       NOT NULL,
    usuario_id    integer       NOT NULL,
    texto         varchar(1000) NOT NULL,
    data_criacao  timestamptz   NOT NULL DEFAULT now(),
    CONSTRAINT pk_tarefa_comentarios PRIMARY KEY (id),
    CONSTRAINT fk_tarefa_comentarios_tarefas FOREIGN KEY (tarefa_id) REFERENCES pim.tarefas (id),
    CONSTRAINT fk_tarefa_comentarios_usuarios FOREIGN KEY (usuario_id) REFERENCES pim.usuarios (id),
    CONSTRAINT ck_tarefa_comentarios_texto CHECK (length(btrim(texto)) > 0)
);
CREATE INDEX IF NOT EXISTS ix_tarefa_comentarios_tarefa_id ON pim.tarefa_comentarios (tarefa_id, data_criacao);

CREATE TABLE IF NOT EXISTS pim.tarefa_historico (
    id               integer GENERATED BY DEFAULT AS IDENTITY,
    tarefa_id        integer      NOT NULL,
    status_anterior  varchar(20)  NOT NULL,
    status_novo      varchar(20)  NOT NULL,
    usuario_id       integer      NULL,
    data_alteracao   timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT pk_tarefa_historico PRIMARY KEY (id),
    CONSTRAINT fk_tarefa_historico_tarefas FOREIGN KEY (tarefa_id) REFERENCES pim.tarefas (id),
    CONSTRAINT fk_tarefa_historico_usuarios FOREIGN KEY (usuario_id) REFERENCES pim.usuarios (id),
    CONSTRAINT ck_tarefa_historico_status CHECK (
        status_anterior IN ('Pendente', 'EmAndamento', 'Concluida') AND
        status_novo     IN ('Pendente', 'EmAndamento', 'Concluida'))
);
CREATE INDEX IF NOT EXISTS ix_tarefa_historico_tarefa_id ON pim.tarefa_historico (tarefa_id, data_alteracao);

/* ---------- view ---------- */
CREATE OR REPLACE VIEW pim.vw_tarefas_detalhadas WITH (security_invoker = true) AS
SELECT t.id, t.titulo, t.descricao, t.status, t.prioridade, t.data_prazo, t.excluida,
       t.data_criacao, t.data_atualizacao,
       t.colaborador_id, c.nome AS colaborador_nome, c.cargo AS colaborador_cargo,
       t.equipe_id,      e.nome AS equipe_nome
FROM pim.tarefas t
LEFT JOIN pim.colaboradores c ON c.id = t.colaborador_id
LEFT JOIN pim.equipes e       ON e.id = t.equipe_id;
